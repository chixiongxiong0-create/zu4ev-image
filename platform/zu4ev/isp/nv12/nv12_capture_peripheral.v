`timescale 1ns/1ps
// Single video-clock peripheral. A separate AXI clock converter is required
// when the PS control master is in another clock domain.
module nv12_capture_peripheral #(
    parameter integer WIDTH=1280, HEIGHT=1024, FIFO_DEPTH=256
) (
    input wire clk, resetn,
    input wire [31:0] s_data,
    input wire s_valid, s_sof, s_eol, s_fault,
    output wire irq,
    input wire [7:0] s_axi_awaddr,
    input wire s_axi_awvalid,
    output wire s_axi_awready,
    input wire [31:0] s_axi_wdata,
    input wire [3:0] s_axi_wstrb,
    input wire s_axi_wvalid,
    output wire s_axi_wready,
    output wire [1:0] s_axi_bresp,
    output wire s_axi_bvalid,
    input wire s_axi_bready,
    input wire [7:0] s_axi_araddr,
    input wire s_axi_arvalid,
    output wire s_axi_arready,
    output wire [31:0] s_axi_rdata,
    output wire [1:0] s_axi_rresp,
    output wire s_axi_rvalid,
    input wire s_axi_rready,
    output wire [31:0] m_axi_awaddr,
    output wire [7:0] m_axi_awlen,
    output wire [2:0] m_axi_awsize,
    output wire [1:0] m_axi_awburst,
    output wire m_axi_awvalid,
    input wire m_axi_awready,
    output wire [127:0] m_axi_wdata,
    output wire [15:0] m_axi_wstrb,
    output wire m_axi_wlast,
    output wire m_axi_wvalid,
    input wire m_axi_wready,
    input wire [1:0] m_axi_bresp,
    input wire m_axi_bvalid,
    output wire m_axi_bready
);
    wire cfg_valid, cfg_ready, cfg_error, release_error;
    wire capture_enable, capture_idle, stop_request;
    wire [1:0] cfg_slot;
    wire [31:0] cfg_base, cfg_stride;
    wire frame_valid, frame_ready, release_valid, irq_enable;
    wire [31:0] frame_base, frame_stride, frame_tag, release_tag;
    wire [31:0] dropped_frames, failed_frames;
    nv12_axi_regs registers (
        .capture_enable(capture_enable),.capture_idle(capture_idle),.stop_request(stop_request),
        .clk(clk),.resetn(resetn),
        .s_axi_awaddr(s_axi_awaddr),
        .s_axi_awvalid(s_axi_awvalid),
        .s_axi_awready(s_axi_awready),
        .s_axi_wdata(s_axi_wdata),
        .s_axi_wstrb(s_axi_wstrb),
        .s_axi_wvalid(s_axi_wvalid),
        .s_axi_wready(s_axi_wready),
        .s_axi_bresp(s_axi_bresp),
        .s_axi_bvalid(s_axi_bvalid),
        .s_axi_bready(s_axi_bready),
        .s_axi_araddr(s_axi_araddr),
        .s_axi_arvalid(s_axi_arvalid),
        .s_axi_arready(s_axi_arready),
        .s_axi_rdata(s_axi_rdata),
        .s_axi_rresp(s_axi_rresp),
        .s_axi_rvalid(s_axi_rvalid),
        .s_axi_rready(s_axi_rready),
        .cfg_valid(cfg_valid),
        .cfg_ready(cfg_ready),
        .cfg_error(cfg_error),
        .release_error(release_error),
        .cfg_slot(cfg_slot),
        .cfg_base(cfg_base),
        .cfg_stride(cfg_stride),
        .frame_valid(frame_valid),
        .frame_ready(frame_ready),
        .frame_base(frame_base),
        .frame_stride(frame_stride),
        .frame_tag(frame_tag),
        .release_valid(release_valid),
        .release_tag(release_tag),
        .irq_enable(irq_enable),
        .dropped_frames(dropped_frames),
        .failed_frames(failed_frames)
    );
    nv12_capture_output #(.WIDTH(WIDTH),.HEIGHT(HEIGHT),.FIFO_DEPTH(FIFO_DEPTH)) capture (
        .enable(capture_enable),.stop_request(stop_request),.idle(capture_idle),
        .clk(clk),.resetn(resetn),.s_data(s_data),.s_valid(s_valid),
        .s_sof(s_sof),.s_eol(s_eol),.s_fault(s_fault),.irq(irq),
        .cfg_valid(cfg_valid),
        .cfg_ready(cfg_ready),
        .cfg_error(cfg_error),
        .release_error(release_error),
        .cfg_slot(cfg_slot),
        .cfg_base(cfg_base),
        .cfg_stride(cfg_stride),
        .frame_valid(frame_valid),
        .frame_ready(frame_ready),
        .frame_base(frame_base),
        .frame_stride(frame_stride),
        .frame_tag(frame_tag),
        .release_valid(release_valid),
        .release_tag(release_tag),
        .irq_enable(irq_enable),
        .dropped_frames(dropped_frames),
        .failed_frames(failed_frames),
        .m_axi_awaddr(m_axi_awaddr),
        .m_axi_awlen(m_axi_awlen),
        .m_axi_awsize(m_axi_awsize),
        .m_axi_awburst(m_axi_awburst),
        .m_axi_awvalid(m_axi_awvalid),
        .m_axi_awready(m_axi_awready),
        .m_axi_wdata(m_axi_wdata),
        .m_axi_wstrb(m_axi_wstrb),
        .m_axi_wlast(m_axi_wlast),
        .m_axi_wvalid(m_axi_wvalid),
        .m_axi_wready(m_axi_wready),
        .m_axi_bresp(m_axi_bresp),
        .m_axi_bvalid(m_axi_bvalid),
        .m_axi_bready(m_axi_bready)
    );
endmodule
